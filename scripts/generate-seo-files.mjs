/** Writes robots.txt and sitemap.xml into client/public/ from the one route list.
 *
 * Runs as part of `npm run build` rather than being committed as static files, because a
 * hand-maintained sitemap is a sitemap that silently goes stale: the page gets added, the XML
 * does not, and nobody notices because nothing breaks. Generated from shared/public-routes.ts,
 * the same list the prerenderer walks.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const outDir = path.join(root, "client", "public");

// The route list is TypeScript; read and strip types rather than adding a build step to consume
// one small array. Deliberately a parse of the literal, not a regex over the whole file, so a
// malformed entry fails loudly here instead of producing a quietly incomplete sitemap.
const src = fs.readFileSync(path.join(root, "shared", "public-routes.ts"), "utf8");

function parseRoutes() {
  const start = src.indexOf("export const PUBLIC_ROUTES");
  const open = src.indexOf("[", start);
  const end = src.indexOf("\n];", open);
  if (start < 0 || open < 0 || end < 0) {
    throw new Error("Could not find PUBLIC_ROUTES in shared/public-routes.ts");
  }
  const body = src.slice(open, end + 2);
  const routes = [];
  for (const m of body.matchAll(/\{([^{}]*)\}/g)) {
    const chunk = m[1];
    const pick = (key) => {
      const hit = chunk.match(new RegExp(`${key}:\\s*("(?:[^"\\\\]|\\\\.)*"|true|false|[\\d.]+)`));
      if (!hit) return undefined;
      const raw = hit[1];
      if (raw === "true") return true;
      if (raw === "false") return false;
      if (raw.startsWith('"')) return JSON.parse(raw);
      return Number(raw);
    };
    const p = pick("path");
    if (!p) continue;
    routes.push({ path: p, index: pick("index"), priority: pick("priority") });
  }
  if (routes.length === 0) throw new Error("Parsed zero public routes -- refusing to write an empty sitemap");
  return routes;
}

function parseNoindexPrefixes() {
  const start = src.indexOf("export const NOINDEX_PREFIXES");
  const open = src.indexOf("[", start);
  const end = src.indexOf("]", open);
  return src
    .slice(open + 1, end)
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s.startsWith('"'))
    .map((s) => JSON.parse(s));
}

const origin = (process.env.VITE_PUBLIC_ORIGIN || "https://forgeperformancesystems.com").replace(/\/$/, "");
const routes = parseRoutes();
const noindex = parseNoindexPrefixes();
const indexable = routes.filter((r) => r.index);

// Today's date, not a per-route timestamp: every one of these pages is generated from the same
// build, so claiming individual modification dates would be inventing precision.
const today = new Date().toISOString().slice(0, 10);

const urls = indexable
  .map(
    (r) =>
      `  <url>\n    <loc>${origin}${r.path === "/" ? "/" : r.path}</loc>\n    <lastmod>${today}</lastmod>\n    <priority>${(r.priority ?? 0.5).toFixed(1)}</priority>\n  </url>`,
  )
  .join("\n");

fs.writeFileSync(
  path.join(outDir, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
);

// Disallow is belt and braces alongside the per-page noindex tag: robots.txt stops the crawl,
// the meta tag stops the indexing of anything reached another way (a link in an email, say).
// Neither alone covers both cases.
// No trailing slash: "Disallow: /reset-password" matches the token URLs too
// ("/reset-password?token=..."), where "/reset-password/" would match only subpaths and let the
// actual page through -- which is the one form it ever appears in.
const disallow = noindex.map((p) => `Disallow: ${p}`).join("\n");

fs.writeFileSync(
  path.join(outDir, "robots.txt"),
  `# Generated by scripts/generate-seo-files.mjs -- edit shared/public-routes.ts, not this file.
User-agent: *
Allow: /
${disallow}

# Reachable without a session, but one-shot token pages with nothing to rank.
Disallow: /forgot-password
Disallow: /signup

Sitemap: ${origin}/sitemap.xml
`,
);

console.log(`SEO files written: ${indexable.length} indexable routes, ${noindex.length} disallowed prefixes.`);
