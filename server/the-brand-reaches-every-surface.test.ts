import { readFileSync } from "node:fs";
import { describe, expect, it, vi } from "vitest";

// EVERY SURFACE THAT PROMISES A PROGRAM'S BRAND CARRIES IT (Scott, 2026-11-19: "pure
// personalization, every aspect of the app that we can change"). Five that missed it:
// the athletes' tab names, the take-away PDFs, the calendar feed, push titles, share cards.

vi.mock("./storage", () => ({ storage: { getEffectiveBrandingForUser: vi.fn() } }));

const PDF_CALL_SITES = 4;
// Strips /* block */ comments, then whole-line // comments: "  // note" goes, "a // b" stays.
// https://regex101.com/?regex=%5E%5Cs*%5C%2F%5C%2F.*%24
const raw = (p: string) => readFileSync(new URL(p, import.meta.url), "utf8");
// Only the negative check strips comments; the positive ones read the file as written, because a
// non-greedy block strip pairs a "/*" inside a string in routes.ts with a "*/" far below it.
const read = (p: string) => raw(p).replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

describe("the take-away PDFs", () => {
  it("name the program in the footer, and Forge alone when there is none", async () => {
    const { pdfGeneratedBy } = await import("./pdf-brand");
    expect(pdfGeneratedBy({ teamName: "Cal Strength", primaryColor: "#003262", logoBuffer: null })).toBe(
      "Generated by Cal Strength via Forge",
    );
    expect(pdfGeneratedBy(null)).toBe("Generated by Forge");
  });

  it("are drawn through the shared band, never a hard-coded FORGE header", () => {
    ["./training-history-export.ts", "./recruiting-profile.ts"].forEach((f) => {
      const src = read(f);
      expect(raw(f)).toContain("drawPdfBrandBand(doc, brand,");
      expect(src).not.toContain('.text("FORGE", 50, 30)');
    });
    const routes = raw("./routes.ts");
    expect(routes.split("await pdfBrandForAthlete(").length - 1).toBe(PDF_CALL_SITES);
  });
});

describe("push titles", () => {
  it("lead with the program's name for an athlete on a branded program", () => {
    const src = raw("./push.ts");
    expect(src).toContain(".getEffectiveBrandingForUser(userId)");
    expect(src).toContain("title: `${programName} · ${payload.title}`");
    expect(src).toContain("sendWebPushToUser(userId, branded)");
    expect(src).toContain("sendApnsToUser(userId, branded)");
  });
});

describe("the calendar feed and the athletes' tabs", () => {
  it("names the calendar after the program", () => {
    expect(raw("./routes.ts")).toContain('`${programName || "Forge"} Training — ${user.name}`');
  });

  it("gives an athlete the program's tab names, matched from the coach's tab of the same page", () => {
    const shell = raw("../client/src/components/app-shell.tsx");
    expect(shell).toContain('programNavLabels[item.href.replace(/^\\/athlete\\//, "/coach/")]');
  });

  it("puts the program's name and color on share cards", () => {
    const card = raw("../client/src/lib/share-card.ts");
    expect(card).toContain("COLOR.primary = brand?.primaryColor || FORGE_PRIMARY;");
    expect(card).toContain('ctx.fillText("via Forge"');
    ["../client/src/pages/athlete/progress.tsx", "../client/src/pages/workout.tsx"].forEach((page) => {
      expect(raw(page)).toContain("brand: shareCardBrandFromCache(),");
    });
  });
});
