/**
 * THE HEADER BAND ON A PDF AN ATHLETE TAKES AWAY, IN THEIR PROGRAM'S LOOK (2026-11-19).
 *
 * The training-history export and the recruiting profile were plain Forge orange whatever program
 * the athlete was on, while the movement-screen sheet already wore the coach's logo, name and
 * color. These read the brand the athlete's own app shows (storage.getEffectiveBrandingForUser,
 * already narrowed to what the program's plan allows), so a Free Agent's PDF stays Forge's.
 *
 * Only the band changes: the body ink stays dark grey, because a color chosen to look good as a
 * button can be unreadable as printed body text. "Powered by Forge" stays in the band.
 */
import type PDFDocument from "pdfkit";
import { pickReadableTextHex } from "@shared/color-contrast";
import { storage } from "./storage";
import { readUploadedFile } from "./uploaded-files";

export const FORGE_PDF_ORANGE = "#F65B23";
const BAND_HEIGHT = 90;
const MARGIN = 50;
const LOGO_SIZE = 50;
const LOGO_TOP = 20;
const TEXT_AFTER_LOGO = 112;
/** Type sizes and baselines inside the band, in points. */
const PDF = {
  nameWithLogo: { size: 18, y: 26 },
  subtitleWithLogo: { size: 10, y: 50 },
  poweredWithLogo: { size: 7, y: 66 },
  name: { size: 24, y: 26 },
  subtitle: { size: 10, y: 56 },
  powered: { size: 7, y: 70 },
} as const;

export type PdfBrand = { teamName: string | null; primaryColor: string | null; logoBuffer: Buffer | null };

export async function pdfBrandForAthlete(athleteId: number): Promise<PdfBrand | null> {
  const brand = await storage.getEffectiveBrandingForUser(athleteId);
  if (!brand || !(brand.brandTeamName || brand.brandPrimaryColor || brand.brandLogoUrl)) return null;
  return {
    teamName: brand.brandTeamName ?? null,
    primaryColor: brand.brandPrimaryColor ?? null,
    logoBuffer: await readUploadedFile(brand.brandLogoUrl),
  };
}

export function drawPdfBrandBand(doc: InstanceType<typeof PDFDocument>, brand: PdfBrand | null, subtitle: string): void {
  const band = brand?.primaryColor || FORGE_PDF_ORANGE;
  const ink = pickReadableTextHex(band);
  const name = brand?.teamName || "FORGE";
  doc.rect(0, 0, doc.page.width, BAND_HEIGHT).fill(band);
  const width = doc.page.width - TEXT_AFTER_LOGO - MARGIN;
  if (brand?.logoBuffer) {
    try {
      doc.image(brand.logoBuffer, MARGIN, LOGO_TOP, { fit: [LOGO_SIZE, LOGO_SIZE] });
      doc.fillColor(ink).fontSize(PDF.nameWithLogo.size).font("Helvetica-Bold").text(name, TEXT_AFTER_LOGO, PDF.nameWithLogo.y, { width });
      doc.fontSize(PDF.subtitleWithLogo.size).font("Helvetica").text(subtitle, TEXT_AFTER_LOGO, PDF.subtitleWithLogo.y, { width });
      if (brand.teamName) doc.fontSize(PDF.poweredWithLogo.size).text("Powered by Forge", TEXT_AFTER_LOGO, PDF.poweredWithLogo.y, { width });
      return;
    } catch {
      // An unreadable logo file falls through to the text-only band below.
    }
  }
  doc.fillColor(ink).fontSize(PDF.name.size).font("Helvetica-Bold").text(name, MARGIN, PDF.name.y);
  doc.fontSize(PDF.subtitle.size).font("Helvetica").text(subtitle, MARGIN, PDF.subtitle.y);
  if (brand?.teamName) doc.fontSize(PDF.powered.size).text("Powered by Forge", MARGIN, PDF.powered.y);
}

export function pdfGeneratedBy(brand: PdfBrand | null): string {
  return brand?.teamName ? `Generated by ${brand.teamName} via Forge` : "Generated by Forge";
}
